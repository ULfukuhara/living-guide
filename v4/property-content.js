export function applyPropertyContent(propertyNo, selected) {
  if (String(propertyNo) !== '11300') return selected;
  let result = selected;
  for (const key of ['mailbox', 'bicycle_space', 'internet', 'trash', 'common_area', 'noise', 'pets', 'bike_parking', 'car_parking', 'sales', 'expenses', 'cancellation', 'usac', 'management_other', 'toilet', 'ventilation', 'air_conditioner', 'electricity', 'gas', 'water', 'key', 'moving', 'room_equipment', 'kurasapo_connect', 'drainage', 'heater']) {
    if (selected[key]?.variant === 'casa_11300' && selected[key].blocks?.length) {
      const blocks = selected[key].blocks.flatMap(block => {
        const update = approvedCopy[block.id];
        const amended = update && block.content === update.before ? { ...block, content: update.after } : block;
        if (block.id === 'air_conditioner_casa_11300_002' && !selected[key].blocks.some(item => item.id === 'air_filter_cleaning_image_v1')) {
          return [amended, { id: 'air_filter_cleaning_image_v1', type: 'image', style: 'default', imageUrl: 'https://guide.univ-life.com/v4/air-filter-cleaning-floor-v2.jpg', alt: '床にシートを敷き、取り外したエアコンのフィルターのホコリを掃除機で吸い取る清掃イメージ', caption: 'フィルター清掃のイメージ' }];
        }
        return [amended];
      });
      result = { ...result, [key]: { ...selected[key], blocks, body: blocks.map(block => block.type === 'image' ? block.alt : block.type === 'button' ? block.actionLabel : block.content).join('\n'), hidePanelTitle: true } };
    }
  }
  return result;
}
